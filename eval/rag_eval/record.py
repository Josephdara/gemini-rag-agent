def build_record(
    *,
    run_id,
    run_time,
    config,
    settings,
    dataset_sha256,
    dataset_item_count,
    item_count,
    item_limit,
    item_errors,
    instruction_sha256,
    rubric_sha256,
    metrics,
    harness_version,
    report_path,
):
    return {
        "run_id": run_id,
        "run_time": run_time.isoformat(),
        "dataset_version": config["dataset_version"],
        "dataset_sha256": dataset_sha256,
        "dataset_item_count": dataset_item_count,
        "item_count": item_count,
        "item_limit": item_limit,
        "item_errors": item_errors,
        "chat_model": settings.chat_model,
        "chat_location": settings.chat_location,
        "embedding_model": settings.embedding_model,
        "top_k": settings.top_k,
        "instruction_sha256": instruction_sha256,
        "harness_version": harness_version,
        "evaluation_location": config["evaluation_location"],
        "judge_model": config["judge"]["model"],
        "judge_location": config["judge"]["location"],
        "rubric_version": config["rubric_version"],
        "rubric_sha256": rubric_sha256,
        "metrics": metrics,
        # A run limited to part of the dataset is a smoke test and never counts as a pass.
        "passed": item_limit is None and all(metric["passed"] for metric in metrics),
        "report_path": report_path,
    }
